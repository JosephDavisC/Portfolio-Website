// Extract the real article body (h2/h3 + body paragraphs) for a slug from
// ArticlePage.tsx at build time, so the crawler-visible static fallback stays
// in sync with the rendered article. Caption paragraphs (text-sm/italic) are
// skipped; body paragraphs use the text-lg class.
// Escape bare ampersands only. The negative lookahead leaves real entities
// (&amp; &nbsp; &#39; &#x27;) alone, so this is safe to run on already-escaped text.
// Without it, prose containing a shell redirect like "&>" lands as invalid HTML.
function esc(t) {
  return t.replace(/&(?!(?:[a-zA-Z][a-zA-Z0-9]*|#\d+|#x[0-9a-fA-F]+);)/g, '&amp;');
}

function extractArticleBody(slug) {
  const src = fs.readFileSync(
    path.join(__dirname, '..', 'src', 'pages', 'ArticlePage.tsx'),
    'utf8'
  );
  const marker = `case '${slug}':`;
  const start = src.indexOf(marker);
  if (start === -1) return '';
  const rest = src.slice(start + marker.length);
  const nextCase = rest.search(/case '|default:/);
  const section = nextCase === -1 ? rest : rest.slice(0, nextCase);
  const out = [];
  // (?![a-zA-Z]) stops <pre> matching as a <p> tag. Without it the regex swallows
  // the code block AND the paragraph after it, which then silently drops out.
  // img is self-closing so it gets its own alternative below. Captions are the
  // italic text-sm paragraphs that follow an image; they are emitted as
  // figcaption rather than skipped, because they carry meaning a crawler needs
  // ("What people were supposed to see" / "What they got instead").
  const re = /<(h2|h3|pre|p)(?![a-zA-Z])([^>]*)>([\s\S]*?)<\/\1>|<img\s([^>]*?)\/?>/g;
  let m;
  while ((m = re.exec(section))) {
    const [, tag, attrs, inner, imgAttrs] = m;

    // Images inline, at the position they appear in the article, so a crawler
    // reads the picture next to the sentence it belongs to.
    if (imgAttrs !== undefined) {
      const src = (imgAttrs.match(/src="([^"]+)"/) || [])[1];
      const alt = (imgAttrs.match(/alt="([^"]*)"/) || [])[1] || '';
      if (src && !src.includes('${')) {
        out.push(`<img src="${src}" alt="${esc(alt)}">`);
      }
      continue;
    }
    // Code and terminal blocks: keep them verbatim in the crawler fallback.
    // Without this the prerendered page reads "sent me this:" followed by nothing,
    // and an LLM reader sees the post as a story with holes where the evidence is.
    if (tag === 'pre') {
      const lit = inner.match(/\{\s*`([\s\S]*?)`\s*\}/);
      const code = (lit ? lit[1] : inner)
        // undo template-literal escaping so shell snippets read as written:
        // \${VAR} in source is a literal ${VAR}, \` is a literal backtick
        .replace(/\\\$\{/g, '${')
        .replace(/\\`/g, '`')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');
      if (code.trim()) out.push(`<pre>${code}</pre>`);
      continue;
    }
    const isCaption = tag === 'p' && attrs.includes('italic');
    if (tag === 'p' && !attrs.includes('text-lg') && !isCaption) continue;
    const text = inner
      .replace(/\{\s*(['"`])([\s\S]*?)\1\s*\}/g, '$2')
      .replace(/\{[^}]*\}/g, ' ')
      .replace(/<[^>]+>/g, ' ')
      .replace(/&nbsp;/g, ' ')
      .replace(/\s+/g, ' ')
      .trim();
    if (text) {
      const outTag = isCaption ? 'figcaption' : tag;
      out.push(`<${outTag}>${esc(text)}</${outTag}>`);
    }
  }
  const html = out.join('');

  // Build-time guard. The fallback is a SECOND copy of the article, generated by
  // regex from the same source, and only one of them gets proofread. When the two
  // diverge nothing complains: the word count still looks plausible, the page
  // still builds, and prose quietly disappears from what crawlers and AI readers
  // see. That has happened twice, once when <pre> matched as a <p> and ate the
  // paragraph after every code block.
  //
  // So assert it instead of trusting it: every heading and every text-lg body
  // paragraph in the source must survive into the fallback, or the build fails.
  // Deliberately NOT checked: paragraphs without text-lg (callout labels and the
  // like are excluded by design) and anything inside <pre>.
  const norm = (t) => t.replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
  const flat = norm(html.replace(/<[^>]+>/g, ' '));
  const missing = [];

  for (const [, heading] of section.matchAll(/<h[23][^>]*>([^<]+)<\/h[23]>/g)) {
    const t = norm(heading);
    if (t && !flat.includes(t.slice(0, 30))) missing.push(`h2/h3: ${t.slice(0, 60)}`);
  }
  for (const [, attrs, body] of section.matchAll(/<p className="([^"]*)">([\s\S]*?)<\/p>/g)) {
    if (!attrs.includes('text-lg')) continue;
    const t = norm(
      body
        .replace(/\{\s*(['"`])([\s\S]*?)\1\s*\}/g, '$2')
        .replace(/\{[^}]*\}/g, ' ')
        .replace(/<[^>]+>/g, ' ')
    );
    if (t && !flat.includes(t.slice(0, 40))) missing.push(`paragraph: ${t.slice(0, 70)}`);
  }

  if (missing.length) {
    console.error(`\n[blog] FALLBACK MISMATCH for "${slug}". These exist in ArticlePage.tsx but did not survive into the crawler-visible fallback:`);
    missing.forEach((x) => console.error(`   - ${x}`));
    throw new Error(`Crawler fallback for "${slug}" is missing ${missing.length} block(s) from the article source.`);
  }

  return html;
}

